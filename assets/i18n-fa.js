const FA_PATTERNS = [
  [/^(\d+) de (\d+) unidades completadas$/, (m) => `${m[1]} از ${m[2]} درس کامل شده`],
  [/^(\d+)\/(\d+) unidades$/, (m) => `${m[1]}/${m[2]} درس`],
  [/^(\d+) d[ií]as$/, (m) => `${m[1]} روز`],
  [/^(\d+) de (\d+)$/, (m) => `${m[1]} از ${m[2]}`]
];

function faText(key){
  if(UI_FA[key]) return UI_FA[key];
  for(const [re, fn] of FA_PATTERNS){
    const m = key.match(re);
    if(m) return fn(m);
  }
  return null;
}

